const DICTS: Record<Lang, Dict> = { en, es, pt };
const LOCALE: Record<Lang, string> = { en: "en-US", es: "es-AR", pt: "pt-BR" };

function detect(): Lang {
  try {
    const saved = localStorage.getItem("cruce.lang") as Lang | null;
    if (saved && LANGS.includes(saved)) return saved;
  } catch {
    // storage blocked
  }
  const nav = (typeof navigator !== "undefined" ? navigator.language : "en").slice(0, 2);
  return (LANGS as string[]).includes(nav) ? (nav as Lang) : "en";
}

interface I18n {
  lang: Lang;
  locale: string;
  setLang(l: Lang): void;
  t(key: Key, vars?: Record<string, string | number>): string;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detect);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const value = useMemo<I18n>(
    () => ({
      lang,
      locale: LOCALE[lang],
      setLang(l) {
        setLangState(l);
        try {
          localStorage.setItem("cruce.lang", l);
        } catch {
          // storage blocked
        }
      },
      t(key, vars) {
        let s: string = DICTS[lang][key] ?? en[key];
        for (const [k, v] of Object.entries(vars ?? {})) s = s.replace(`{${k}}`, String(v));
        return s;
      },
    }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}
